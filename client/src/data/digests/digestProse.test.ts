describe("산문에 남아야 하는 계산 결과", () => {
  for (const { route, digest } of ENGINE_DIGESTS) {
    const sections = findingSections(digest);
    const expectations = EXPECTED[route];

    it(`${route}: 앵커 표가 발견 수와 맞는다`, () => {
      expect(Object.keys(expectations ?? {}).map(Number).sort((a, b) => a - b)).toEqual(
        sections.map((_, index) => index + 1),
      );
    });

    for (const [index, needles] of Object.entries(expectations ?? {})) {
      it(`${route} 발견 ${index}: 기대한 계산값이 문장에 남아 있다`, () => {
        const section = sections[Number(index) - 1];
        const text = `${section.h2} ${section.body}`;
        for (const needle of needles) expect(text, `${section.h2} / ${needle}`).toContain(needle);
      });
    }
  }
});
